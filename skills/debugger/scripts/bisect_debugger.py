#!/usr/bin/env python3
"""
bisect_debugger.py — Root-Cause Debugging & Git Bisect Engine

Provides automated stack trace analysis, minimal reproduction test harness generation,
and automated git bisection for regressions.

Usage:
    python3 bisect_debugger.py --analyze-trace /path/to/trace.txt
    python3 bisect_debugger.py --repro "python3 -m unittest tests/test_fail.py" --output repro.py
    python3 bisect_debugger.py --bisect --test "pytest tests/test_feature.py" --good v1.0.0 --bad HEAD
"""

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional


def analyze_trace_text(trace: str) -> Dict[str, Any]:
    """Parses Python, JavaScript/TypeScript, Swift, and Go stack traces."""
    lines = trace.strip().splitlines()
    frames = []
    error_type = "UnknownError"
    error_message = ""

    # Python pattern: File "...", line 123, in func
    py_pattern = re.compile(r'File "([^"]+)", line (\d+), in (\w+)')
    # JS/TS pattern: at func (/path/to/file.ts:123:45)
    js_pattern = re.compile(r'at (?:(\S+) )?\(?([^:]+):(\d+)(?::\d+)?\)?')
    # Go pattern: /path/to/file.go:123 +0x45
    go_pattern = re.compile(r'(\S+\.go):(\d+)')

    for line in lines:
        line_clean = line.strip()
        py_match = py_pattern.search(line_clean)
        if py_match:
            frames.append({
                "file": py_match.group(1),
                "line": int(py_match.group(2)),
                "function": py_match.group(3),
                "raw": line_clean
            })
            continue

        js_match = js_pattern.search(line_clean)
        if js_match:
            frames.append({
                "file": js_match.group(2),
                "line": int(js_match.group(3)),
                "function": js_match.group(1) or "<anonymous>",
                "raw": line_clean
            })
            continue

        go_match = go_pattern.search(line_clean)
        if go_match:
            frames.append({
                "file": go_match.group(1),
                "line": int(go_match.group(2)),
                "function": "<unknown>",
                "raw": line_clean
            })
            continue

        # Look for exception line (e.g. ValueError: message or TypeError:)
        if ":" in line_clean and not line_clean.startswith("at ") and not line_clean.startswith("File "):
            parts = line_clean.split(":", 1)
            candidate_type = parts[0].strip()
            if candidate_type.endswith("Error") or candidate_type.endswith("Exception"):
                error_type = candidate_type
                error_message = parts[1].strip()

    origin_frame = frames[-1] if frames else None

    return {
        "error_type": error_type,
        "error_message": error_message,
        "total_frames": len(frames),
        "frames": frames,
        "origin_frame": origin_frame,
        "suggested_file": origin_frame["file"] if origin_frame else None,
        "suggested_line": origin_frame["line"] if origin_frame else None,
    }


def generate_reproduction_script(command: str, output_path: str = "repro.sh") -> str:
    """Creates a deterministic shell or python reproduction script."""
    path = Path(output_path)
    if path.suffix == ".py":
        script_content = f'''#!/usr/bin/env python3
"""
Minimal Bug Reproduction Harness
Generated by bisect_debugger.py

Expected behavior: Exits 1 when bug is present (Red), exits 0 when resolved (Green).
"""
import subprocess
import sys

def main():
    print("🧪 Executing reproduction target...")
    cmd = {repr(command)}
    result = subprocess.run(cmd, shell=True)
    if result.returncode != 0:
        print(f"❌ Reproduction confirmed: target failed with code {{result.returncode}}")
        sys.exit(1)
    print("✅ Target passed with code 0! Bug resolved.")
    sys.exit(0)

if __name__ == "__main__":
    main()
'''
    elif path.suffix == ".ps1":
        script_content = f'''#!/usr/bin/env pwsh
# Minimal Bug Reproduction Harness
# Generated by bisect_debugger.py
# Exits 1 when failing (Red), exits 0 when resolved (Green).

$ErrorActionPreference = 'Continue'
Write-Host "🧪 Running reproduction target: {command}"
Invoke-Expression {repr(command)}
if ($LASTEXITCODE -and $LASTEXITCODE -ne 0) {{
    Write-Host "❌ Reproduction confirmed: target failed with exit code $LASTEXITCODE"
    exit 1
}}
Write-Host "✅ Target succeeded (exit 0). Bug resolved."
exit 0
'''
    else:
        script_content = f'''#!/usr/bin/env bash
# Minimal Bug Reproduction Harness
# Generated by bisect_debugger.py
# Exits 1 when failing (Red), exits 0 when resolved (Green).

set -u

echo "🧪 Running reproduction target: {command}"
{command}
EXIT_CODE=$?

if [ $EXIT_CODE -ne 0 ]; then
    echo "❌ Reproduction confirmed: target failed with exit code $EXIT_CODE"
    exit 1
fi

echo "✅ Target succeeded (exit 0). Bug resolved."
exit 0
'''

    path.write_text(script_content, encoding="utf-8")
    path.chmod(0o755)
    return str(path)


def run_git_bisect(test_cmd: str, good_rev: Optional[str] = None, bad_rev: Optional[str] = "HEAD") -> Dict[str, Any]:
    """Runs automated git bisect using the given test command."""
    try:
        # Start bisect
        subprocess.run(["git", "bisect", "reset"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        subprocess.run(["git", "bisect", "start"], check=True)

        bad_target = bad_rev or "HEAD"
        subprocess.run(["git", "bisect", "bad", bad_target], check=True)

        if good_rev:
            subprocess.run(["git", "bisect", "good", good_rev], check=True)
        else:
            # Try to find a recent good commit, or fail gracefully
            print("⚠️ No good revision provided. Bisect start requires a known good commit.")
            subprocess.run(["git", "bisect", "reset"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            return {"status": "error", "message": "Good revision required (e.g. --good v1.0.0 or a git SHA)"}

        # Run automated bisect script
        res = subprocess.run(["git", "bisect", "run", "sh", "-c", test_cmd], capture_output=True, text=True)
        bisect_output = res.stdout + res.stderr

        # Extract culprit commit
        culprit_match = re.search(r"([0-9a-f]{7,40}) is the first bad commit", bisect_output)
        culprit = culprit_match.group(1) if culprit_match else None

        subprocess.run(["git", "bisect", "reset"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

        return {
            "status": "success" if culprit else "inconclusive",
            "culprit_commit": culprit,
            "raw_output": bisect_output.strip()
        }
    except Exception as e:
        subprocess.run(["git", "bisect", "reset"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        return {"status": "error", "message": str(e)}


def main():
    parser = argparse.ArgumentParser(description="Universal Root-Cause Debugger & Git Bisect Engine.")
    parser.add_argument("--analyze-trace", type=str, help="Path to stack trace file or raw trace string")
    parser.add_argument("--repro", type=str, help="Command to wrap in a minimal reproduction harness")
    parser.add_argument("--output", type=str, default="repro.sh", help="Output path for reproduction script")
    parser.add_argument("--bisect", action="store_true", help="Run automated git bisect")
    parser.add_argument("--test", type=str, help="Test command to run at each bisect step")
    parser.add_argument("--good", type=str, help="Known good git commit or tag for bisect")
    parser.add_argument("--bad", type=str, default="HEAD", help="Known bad git commit (default: HEAD)")
    parser.add_argument("--json", action="store_true", help="Output result in JSON format")

    args = parser.parse_args()

    if args.analyze_trace:
        path = Path(args.analyze_trace)
        trace_text = path.read_text(encoding="utf-8") if path.exists() else args.analyze_trace
        analysis = analyze_trace_text(trace_text)
        if args.json:
            print(json.dumps(analysis, indent=2))
        else:
            print("🔍 Stack Trace Analysis:")
            print(f"   • Error: {analysis['error_type']}: {analysis['error_message']}")
            print(f"   • Total Frames: {analysis['total_frames']}")
            if analysis['suggested_file']:
                print(f"   • Culprit Origin: {analysis['suggested_file']}:{analysis['suggested_line']}")
        return

    if args.repro:
        script_path = generate_reproduction_script(args.repro, args.output)
        print(f"✅ Generated minimal reproduction harness: {script_path}")
        print(f"   Run via: ./{script_path}")
        return

    if args.bisect:
        if not args.test or not args.good:
            print("❌ Error: --bisect requires both --test '<command>' and --good '<commit/tag>'")
            sys.exit(1)
        print(f"🧭 Starting automated git bisect between {args.good} and {args.bad}...")
        result = run_git_bisect(args.test, good_rev=args.good, bad_rev=args.bad)
        if args.json:
            print(json.dumps(result, indent=2))
        else:
            if result.get("culprit_commit"):
                print(f"🎯 Regression isolated! Culprit commit: {result['culprit_commit']}")
            else:
                print(f"⚠️ Bisect status: {result['status']}: {result.get('message', 'Check output')}")
        return

    parser.print_help()


if __name__ == "__main__":
    main()
